function satisfied(p, evidence, completeCoverage) {
  return evidence?.type === p.type && evidence?.status === p.status &&
    (!p.fullCoverage || completeCoverage(evidence));
}
function rows(evidence, completeCoverage = () => false) {
  const byId = new Map(evidence.map(e => [e.id, e]));
  return tasks.map(task => ({ ...task, status: task.prerequisites.every(id =>
    satisfied(prerequisites[id], byId.get(prerequisites[id].evidence), completeCoverage)) ? "READY" : "BLOCKED" }));
}
